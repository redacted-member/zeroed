export type MenuCommand = (typeof MENU_COMMANDS)[number];

const MENU_COMMAND_SET: ReadonlySet<string> = new Set(MENU_COMMANDS);

/** Whether `id` names a menu command the page answers. */
export function isMenuCommand(id: string): id is MenuCommand {
  return MENU_COMMAND_SET.has(id);
}
